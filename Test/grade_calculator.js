let grade = 100;
if (grade >=90 && grade <=100) {
    console.log("A grade");
} else if (grade >=80 && grade <90) {
    console.log("B grade");
} else if (grade >=70 && grade <80) {
    console.log("C grade");
} else if (grade >=60 && grade <70) {
    console.log("D grade");
} else if (grade >=0 && grade <60) {
    console.log("F grade");
}   else {
    console.log("invalid grade");
}
